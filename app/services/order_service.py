
from datetime import datetime, timezone
from decimal import Decimal
from uuid import uuid4

from app.engine.matching_engine import MatchingEngine
from app.engine.models import Order, OrderSide as EngineOrderSide
from app.schemas.order import OrderCreate

from app.database.repository import (
    create_order as save_order,
    update_order,
    save_trade,
)


# One engine instance must be shared across API requests.
matching_engine = MatchingEngine()


def _timestamp(value: datetime) -> str:
    return value.isoformat()


def _database_status(engine_status) -> str:
    # The existing database/API uses NEW rather than OPEN.
    if engine_status.value == "OPEN":
        return "NEW"
    return engine_status.value


def submit_order(request: OrderCreate) -> dict:
    """Submit an order to the matching engine and persist its results."""

    now = datetime.now(timezone.utc)
    order_id = str(uuid4())

    engine_order = Order(
        order_id=order_id,
        symbol=request.symbol,
        side=EngineOrderSide(request.side.value),
        price=Decimal(str(request.limit_price)),
        quantity=request.quantity,
        created_at=now,
        updated_at=now,
    )

    # Keep references to existing orders before matching.
    # The engine may remove fully filled orders from its book.
    book = matching_engine.get_order_book(engine_order.symbol)
    resting_orders = dict(book.orders_by_id)

    # Match the incoming order.
    generated_trades = matching_engine.process_order(engine_order)
    print("ENGINE ORDER:", engine_order.order_id, engine_order.order_status)
    print("GENERATED TRADES:", len(generated_trades))
    print("BOOK ORDER IDS:", list(book.orders_by_id.keys()))

    # Save the incoming order first so trade foreign keys are valid.
    record = {
        "order_id": engine_order.order_id,
        "symbol": engine_order.symbol,
        "side": engine_order.side.value,
        "limit_price": str(engine_order.price),
        "quantity": engine_order.quantity,
        "remaining_quantity": engine_order.remaining_quantity,
        "status": _database_status(engine_order.order_status),
        "created_at": _timestamp(engine_order.created_at),
        "updated_at": _timestamp(engine_order.updated_at),
    }
    saved = save_order(record)

    # Persist the changed quantities/statuses of previously resting orders.
    for resting in resting_orders.values():
        update_order(
            resting.order_id,
            {
                "remaining_quantity": resting.remaining_quantity,
                "status": _database_status(resting.order_status),
            },
        )

    # Persist every trade generated by this submission.
    for trade in generated_trades:
        save_trade({
            "trade_id": trade.trade_id,
            "symbol": trade.symbol,
            "buy_order_id": trade.buy_order_id,
            "sell_order_id": trade.sell_order_id,
            "execution_price": str(trade.price),
            "quantity": trade.quantity,
            "executed_at": _timestamp(trade.executed_at),
        })

    # Return the latest database record, including any fills.
    from app.database.repository import get_order

    result = get_order(order_id)
    return result if result is not None else saved
